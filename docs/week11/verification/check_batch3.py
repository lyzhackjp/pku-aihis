"""第十一周第三批浏览器验收（D08、D19、D22、D20 进阶）｜2026-11-26"""
import sys, json, re, os
from playwright.sync_api import sync_playwright
OUT = sys.argv[1]; os.makedirs(OUT, exist_ok=True)
BASE = 'http://127.0.0.1:8782/prototype/index.html'
res = []; errs = []
def ok(name, cond, note=''):
    res.append({'check': name, 'pass': bool(cond), 'note': note}); print(('PASS ' if cond else 'FAIL ') + name + ('｜' + note if note else ''))
def goto(page, pid): page.evaluate(f"location.hash = '#{pid}'"); page.wait_for_timeout(500)
def slide(page, pid): return page.locator(f'deck-slide[slide-id="{pid}"]')
def text(page, pid): return slide(page, pid).inner_text()
with sync_playwright() as p:
    b = p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
    for mode in ['local', 'public']:
        ctx = b.new_context(viewport={'width': 1440, 'height': 900}); page = ctx.new_page()
        page.on('pageerror', lambda e, m=mode: errs.append(f'[{m}] pageerror {e}'))
        page.on('console', lambda m, md=mode: errs.append(f'[{md}] console.error {m.text}') if m.type == 'error' and 'favicon' not in m.location.get('url', '') else None)
        page.goto(BASE + ('?pack=../local-only/week11-pack.json' if mode == 'local' else '')); page.wait_for_timeout(1500)
        for pid in ['D08', 'D12', 'D19', 'D20', 'D22']: goto(page, pid); page.screenshot(path=f'{OUT}/{mode}_{pid}.png')
        goto(page, 'D08'); s = slide(page, 'D08'); t = text(page, 'D08')
        ok(f'[{mode}] D08 小例：单次 1/3—2/3，合并 2/3，提示相同集合不增益', '合并召回率 2/3' in t and '1/3' in t and '不重合' in t)
        s.locator('button[data-x="e3"]').click(); page.wait_for_timeout(300)
        ok(f'[{mode}] D08 A-3 改为查出 E3：合并跳到 3/3', '合并召回率 3/3' in text(page, 'D08'))
        s.locator('input[data-g="B-1|E2"]').uncheck(); page.wait_for_timeout(300)
        ok(f'[{mode}] D08 取消 B-1 的 E2：B-1 单次 0/3，合并仍 3/3', '合并召回率 3/3' in text(page, 'D08'))
        ok(f'[{mode}] D08 贪心曲线 SVG', s.locator('svg polyline').count() == 1)
        s.locator('input[name="poolsrc"][value="real"]').check(); page.wait_for_timeout(300)
        ok(f'[{mode}] D08 实际记录：待课前运行', '待课前运行' in text(page, 'D08'))
        s.locator('input[name="truth"][value="real"]').check(); page.wait_for_timeout(200)
        ok(f'[{mode}] D08 植入／真实切换', 'SPOT 的 21.1%' in text(page, 'D08'))
        goto(page, 'D19'); s = slide(page, 'D19')
        s.locator('[data-cell19="2|2"]').click(); page.wait_for_timeout(200)
        ok(f'[{mode}] D19 点格子展开要点与小节', '原文多为日文刊本与扫描本' in text(page, 'D19') and 'D07—D09' in text(page, 'D19'))
        s.locator('select[data-m="sources_in_hand"]').select_option('no'); page.wait_for_timeout(150)
        s.locator('input[data-m="note_count"]').fill('45'); s.locator('input[data-m="note_count"]').dispatch_event('change'); page.wait_for_timeout(150)
        s.locator('select[data-m="problem"]').select_option('引文与转述可疑'); page.wait_for_timeout(300); t = text(page, 'D19')
        ok(f'[{mode}] D19 原文不在手、脚注 45：推荐注释核验 → 逆向大纲，排除深度审读', '注释核验 → 逆向大纲' in t and '原文不在手，不推荐' in t)
        goto(page, 'D22'); s = slide(page, 'D22')
        ok(f'[{mode}] D22 23 张卡', s.locator('article.w11-case').count() == 23)
        s.locator('input[name="cgrp"][value="深度审读"]').check(); page.wait_for_timeout(200)
        n = s.locator('article.w11-case').count(); ok(f'[{mode}] D22 筛"深度审读"', 3 <= n <= 7, str(n))
        s.locator('button[data-open]').first.click(); page.wait_for_timeout(200)
        ok(f'[{mode}] D22 展开十栏', '局限与核验' in text(page, 'D22'))
        s.locator('button[data-go]').first.click(); page.wait_for_timeout(500)
        ok(f'[{mode}] D22 "学生可做"跳到页面', page.evaluate('location.hash') in ('#D07', '#D08', '#D09'), page.evaluate('location.hash'))
        goto(page, 'D20'); s = slide(page, 'D20'); s.locator('summary', has_text='进阶').click(); page.wait_for_timeout(200)
        sels = s.locator('select[data-mine]')
        ok(f'[{mode}] D20 ITERATER 十条载入，附 test.json 行号', sels.count() == 10 and 'test.json 第' in text(page, 'D20'))
        golds = page.evaluate("W11_PUBLIC.iterater.items.map(x=>x.gold_intention)")
        for i in range(10): sels.nth(i).select_option(golds[i] if i < 7 else 'other'); page.wait_for_timeout(80)
        ok(f'[{mode}] D20 标十条，七条与原标注同：7/10', '7/10（70%）' in text(page, 'D20'))
        ctx.close()
    b.close()
ok('全程无页面错误', not errs, '；'.join(errs[:6]))
json.dump({'results': res, 'errors': errs}, open(f'{OUT}/result.json', 'w'), ensure_ascii=False, indent=1)
print(sum(r['pass'] for r in res), '/', len(res))
